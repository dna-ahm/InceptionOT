#!/usr/bin/env bash
set -euo pipefail

NODE_IP="192.168.56.110"
TOKEN_FILE="/vagrant/node-token"

# Remove any leftover token from previous deployments
rm -f "$TOKEN_FILE"

# Detect interface name associated with the private IP (typically eth1 or enp0s8)
IFACE=$(ip -4 -o addr show to "$NODE_IP" | awk '{print $2}' | head -n1)

if [ -z "$IFACE" ]; then
  echo "[-] Error: Could not determine interface for IP $NODE_IP"
  exit 1
fi

echo "[+] Installing K3s Server on $NODE_IP via interface $IFACE..."

# Install K3s server with explicit node-ip, advertise-address, and flannel-iface
curl -sfL https://get.k3s.io | INSTALL_K3S_EXEC="server \
  --bind-address=${NODE_IP} \
  --advertise-address=${NODE_IP} \
  --node-ip=${NODE_IP} \
  --flannel-iface ${IFACE} \
  --write-kubeconfig-mode=644" sh -

# Wait until the token file is generated by K3s
echo "[+] Waiting for K3s node-token generation..."
while [ ! -f /var/lib/rancher/k3s/server/node-token ]; do
  sleep 2
done

# Copy token to the shared folder for worker consumption
cp /var/lib/rancher/k3s/server/node-token "$TOKEN_FILE"
chmod 644 "$TOKEN_FILE"
echo "[+] Token exported to $TOKEN_FILE"

# Configure kubectl environment for the default vagrant user
mkdir -p /home/vagrant/.kube
cp /etc/rancher/k3s/k3s.yaml /home/vagrant/.kube/config
chown -R vagrant:vagrant /home/vagrant/.kube

echo "export KUBECONFIG=/home/vagrant/.kube/config" >> /home/vagrant/.bashrc

# Apps
kubectl apply -f /vagrant/confs/Deployment.app1.yml
kubectl apply -f /vagrant/confs/Service.app1.yml



# Load balancer
kubectl apply -f /vagrant/confs/Ingress.yml
